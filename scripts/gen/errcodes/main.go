// errcodes 从 schemas/common/v1/error-codes.json 生成 Go 常量与文档表。
//
//	go run ./scripts/gen/errcodes          # 写入生成文件
//	go run ./scripts/gen/errcodes -check   # 只核对，不一致时退出码 1
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/oujinhaoai/lantai/internal/contract/schema"
	"github.com/oujinhaoai/lantai/scripts/gen/internal/genfile"
)

const (
	registryPath = "schemas/common/v1/error-codes.json"
	goOutput     = "internal/contract/errcode/codes_gen.go"
	docOutput    = "docs/contracts/error-codes.md"
)

type entry struct {
	Code           string `json:"code"`
	HTTPStatus     int    `json:"http_status"`
	Retryable      bool   `json:"retryable"`
	RecoveryAction string `json:"recovery_action"`
	Owner          string `json:"owner"`
	Summary        string `json:"summary"`
}

type supersededEntry struct {
	Code       string   `json:"code"`
	ReplacedBy []string `json:"replaced_by"`
	Reason     string   `json:"reason"`
}

type registry struct {
	Contract   string            `json:"contract"`
	Codes      []entry           `json:"codes"`
	Superseded []supersededEntry `json:"superseded"`
}

func main() {
	check := flag.Bool("check", false, "compare generated output with files on disk instead of writing")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "errcodes:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	root, err := genfile.Root()
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(filepath.Join(root, registryPath))
	if err != nil {
		return err
	}
	reg, err := schema.Default()
	if err != nil {
		return err
	}
	if err := reg.ValidateJSON("lantai.error-codes/v1", raw); err != nil {
		return err
	}
	var r registry
	if err := json.Unmarshal(raw, &r); err != nil {
		return err
	}
	if err := verify(r); err != nil {
		return err
	}
	goSrc, err := renderGo(r)
	if err != nil {
		return err
	}
	if err := genfile.Output(filepath.Join(root, goOutput), goSrc, check); err != nil {
		return err
	}
	return genfile.Output(filepath.Join(root, docOutput), renderDoc(r), check)
}

// verify 检查 schema 无法表达的一致性规则。
func verify(r registry) error {
	codes := map[string]entry{}
	for _, e := range r.Codes {
		if _, dup := codes[e.Code]; dup {
			return fmt.Errorf("duplicate code %s", e.Code)
		}
		codes[e.Code] = e
		// retryable 表示“不做其他动作、原样重试可能成功”。
		switch e.RecoveryAction {
		case "retry":
			if !e.Retryable {
				return fmt.Errorf("%s: recovery_action retry requires retryable=true", e.Code)
			}
		case "poll_operation", "human_action":
		default:
			if e.Retryable {
				return fmt.Errorf("%s: recovery_action %s requires retryable=false", e.Code, e.RecoveryAction)
			}
		}
		if e.Retryable && e.RecoveryAction != "retry" && e.RecoveryAction != "poll_operation" {
			return fmt.Errorf("%s: retryable codes must suggest retry or poll_operation", e.Code)
		}
	}
	for _, s := range r.Superseded {
		if _, clash := codes[s.Code]; clash {
			return fmt.Errorf("superseded code %s is still registered", s.Code)
		}
		for _, repl := range s.ReplacedBy {
			if _, ok := codes[repl]; !ok {
				return fmt.Errorf("superseded code %s refers to unknown replacement %s", s.Code, repl)
			}
		}
	}
	return nil
}

var initialisms = map[string]string{"TOTP": "TOTP", "HTTP": "HTTP", "ID": "ID", "URL": "URL", "API": "API"}

func goName(code string) string {
	var sb strings.Builder
	for _, w := range strings.Split(code, "_") {
		if up, ok := initialisms[w]; ok {
			sb.WriteString(up)
			continue
		}
		sb.WriteString(w[:1])
		sb.WriteString(strings.ToLower(w[1:]))
	}
	return sb.String()
}

func actionConst(a string) string {
	return "Action" + goName(strings.ToUpper(a))
}

func renderGo(r registry) ([]byte, error) {
	codes := append([]entry(nil), r.Codes...)
	sort.Slice(codes, func(i, j int) bool { return codes[i].Code < codes[j].Code })
	var b bytes.Buffer
	b.WriteString("// Code generated by scripts/gen/errcodes from " + registryPath + ". DO NOT EDIT.\n\n")
	b.WriteString("package errcode\n\n")
	b.WriteString("// 已登记的错误码。\nconst (\n")
	for _, e := range codes {
		fmt.Fprintf(&b, "\t// %s %s\n\t%s Code = %q\n", goName(e.Code), e.Summary, goName(e.Code), e.Code)
	}
	b.WriteString(")\n\n")
	b.WriteString("var specs = []Spec{\n")
	for _, e := range codes {
		fmt.Fprintf(&b, "\t{Code: %s, HTTPStatus: %d, Retryable: %v, Recovery: %s, Owner: %q, Summary: %q},\n",
			goName(e.Code), e.HTTPStatus, e.Retryable, actionConst(e.RecoveryAction), e.Owner, e.Summary)
	}
	b.WriteString("}\n\n")
	sup := append([]supersededEntry(nil), r.Superseded...)
	sort.Slice(sup, func(i, j int) bool { return sup[i].Code < sup[j].Code })
	b.WriteString("// superseded 列出旧草案中已被替代的错误码，服务端不得再返回。\n")
	b.WriteString("var superseded = map[Code][]Code{\n")
	for _, s := range sup {
		var repl []string
		for _, c := range s.ReplacedBy {
			repl = append(repl, goName(c))
		}
		fmt.Fprintf(&b, "\t%q: {%s},\n", s.Code, strings.Join(repl, ", "))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func renderDoc(r registry) []byte {
	codes := append([]entry(nil), r.Codes...)
	sort.Slice(codes, func(i, j int) bool {
		if codes[i].HTTPStatus != codes[j].HTTPStatus {
			return codes[i].HTTPStatus < codes[j].HTTPStatus
		}
		return codes[i].Code < codes[j].Code
	})
	var b bytes.Buffer
	b.WriteString("<!-- Code generated by scripts/gen/errcodes from " + registryPath + ". DO NOT EDIT. -->\n\n")
	b.WriteString("# 错误码表\n\n")
	b.WriteString("唯一来源是 [`" + registryPath + "`](../../" + registryPath + ")，本表与 Go 常量由生成器输出，修改请改注册表后运行 `scripts/generate.sh`。")
	b.WriteString("`retryable` 指不做其他动作、以同一幂等键原样重试是否可能成功；`recovery_action` 的含义见[公共契约](README.md#错误模型)。\n\n")
	b.WriteString("| 错误码 | HTTP | retryable | recovery_action | 所属 | 含义 |\n|---|---:|---|---|---|---|\n")
	for _, e := range codes {
		fmt.Fprintf(&b, "| `%s` | %d | %v | `%s` | %s | %s |\n", e.Code, e.HTTPStatus, e.Retryable, e.RecoveryAction, e.Owner, e.Summary)
	}
	b.WriteString("\n## 已替代的旧草案错误码\n\n服务端不得返回下列错误码；客户端遇到时按替代码理解。\n\n")
	b.WriteString("| 旧错误码 | 替代为 | 原因 |\n|---|---|---|\n")
	sup := append([]supersededEntry(nil), r.Superseded...)
	sort.Slice(sup, func(i, j int) bool { return sup[i].Code < sup[j].Code })
	for _, s := range sup {
		var repl []string
		for _, c := range s.ReplacedBy {
			repl = append(repl, "`"+c+"`")
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", s.Code, strings.Join(repl, "、"), s.Reason)
	}
	return b.Bytes()
}
