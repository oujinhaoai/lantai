// ownership 从 internal/contract/ownership 的登记生成 docs/contracts/ownership.md。
//
//	go run ./scripts/gen/ownership          # 写入
//	go run ./scripts/gen/ownership -check   # 只核对
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/oujinhaoai/lantai/internal/contract/ownership"
	"github.com/oujinhaoai/lantai/scripts/gen/internal/genfile"
)

const output = "docs/contracts/ownership.md"

func main() {
	check := flag.Bool("check", false, "compare generated output with the file on disk instead of writing")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "ownership:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	if err := ownership.Validate(); err != nil {
		return err
	}
	root, err := genfile.Root()
	if err != nil {
		return err
	}
	return genfile.Output(filepath.Join(root, output), render(), check)
}

func render() []byte {
	var b bytes.Buffer
	b.WriteString("<!-- Code generated by scripts/gen/ownership from internal/contract/ownership. DO NOT EDIT. -->\n\n")
	b.WriteString("# 数据、文件与事件所有权\n\n")
	b.WriteString("唯一来源是 [`internal/contract/ownership`](../../internal/contract/ownership/ownership.go)，本表由生成器输出。")
	b.WriteString("规则见[公共契约](README.md#所有权与锁顺序)：每张业务表只有一个模块写入，表名以模块名加下划线开头；")
	b.WriteString("跨模块、跨库不联表、不建外键、不共用 SQL 事务。\n\n")

	b.WriteString("## 模块\n\n| 模块 | 任务 | 职责 |\n|---|---|---|\n")
	for _, m := range ownership.Modules {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", m.Name, m.Task, m.Summary)
	}

	b.WriteString("\n## 数据库\n\n| 库 | 可拥有业务表的模块 | 权威数据 |\n|---|---|---|\n")
	for _, d := range ownership.Databases {
		fmt.Fprintf(&b, "| `%s.db` | %s | %s |\n", d.Database, codeList(d.Owners), d.Summary)
	}

	b.WriteString("\n## 基础设施表\n\n表结构与写入代码由共享组件维护，行按 `owner_module` 归属业务模块；没有全局业务回执库。\n\n")
	b.WriteString("| 表 | 维护组件 | 允许的库 | 用途 |\n|---|---|---|---|\n")
	for _, it := range ownership.InfraTables {
		var dbs []string
		for _, d := range it.Databases {
			dbs = append(dbs, string(d))
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n", it.Name, it.Owner, codeList(dbs), it.Summary)
	}

	b.WriteString("\n## 文件区域\n\n具体目录布局由 storage 与 operations 决定；这里只登记逻辑区域与写入者。\n\n")
	b.WriteString("| 区域 | 写入者 | 内容 |\n|---|---|---|\n")
	for _, f := range ownership.FileAreas {
		fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", f.Name, f.Owner, f.Summary)
	}

	b.WriteString("\n## 事件类型前缀\n\n事件类型第一段决定所属模块；新前缀须先登记。\n\n| 前缀 | 所属模块 |\n|---|---|\n")
	prefixes := make([]string, 0, len(ownership.EventPrefixes))
	for p := range ownership.EventPrefixes {
		prefixes = append(prefixes, p)
	}
	sort.Strings(prefixes)
	for _, p := range prefixes {
		fmt.Fprintf(&b, "| `%s.*` | `%s` |\n", p, ownership.EventPrefixes[p])
	}
	return b.Bytes()
}

func codeList(items []string) string {
	quoted := make([]string, len(items))
	for i, s := range items {
		quoted[i] = "`" + s + "`"
	}
	return strings.Join(quoted, "、")
}
