// identity 从身份模块的动作与策略登记生成 docs/contracts/identity-actions.md。
//
//	go run ./scripts/gen/identity          # 写入
//	go run ./scripts/gen/identity -check   # 只核对
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/oujinhaoai/lantai/internal/contract/authz"
	"github.com/oujinhaoai/lantai/internal/identity"
	"github.com/oujinhaoai/lantai/scripts/gen/internal/genfile"
)

const output = "docs/contracts/identity-actions.md"

func main() {
	check := flag.Bool("check", false, "compare generated output with the file on disk instead of writing")
	flag.Parse()
	root, err := genfile.Root()
	if err == nil {
		err = genfile.Output(filepath.Join(root, output), render(), *check)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "identity:", err)
		os.Exit(1)
	}
}

func render() []byte {
	var b bytes.Buffer
	b.WriteString("<!-- Code generated by scripts/gen/identity from internal/identity. DO NOT EDIT. -->\n\n")
	b.WriteString("# 动作、角色与策略登记\n\n")
	b.WriteString("唯一来源是 [`internal/identity/actions.go`](../../internal/identity/actions.go) 与 [`policy.go`](../../internal/identity/policy.go)，本表由生成器输出。")
	b.WriteString("规则见[身份与授权](identity.md)：未登记的动作一律拒绝；会话范围只收窄，不授予角色之外的权限；")
	b.WriteString("需要人类授权的动作只能经 Challenge → HumanGrant → 敏感命令执行，`Authorize` 对它们返回 `HUMAN_PROOF_REQUIRED`。\n\n")

	b.WriteString("## 主体类别与会话范围上限\n\n| 类别 | 可用范围 |\n|---|---|\n")
	for _, k := range []authz.PrincipalKind{authz.Human, authz.Agent, authz.Node, authz.Worker, authz.Runner, authz.Service} {
		var sc []string
		for _, s := range identity.AllowedScopes(k) {
			sc = append(sc, "`"+string(s)+"`")
		}
		fmt.Fprintf(&b, "| `%s` | %s |\n", k, strings.Join(sc, "、"))
	}
	b.WriteString("\n受限恢复/设置会话只有 `recovery` 与 `self`；委托会话只有所列动作对应的范围与 `self`。\n\n")

	b.WriteString("## 动作\n\n| 动作 | 级别 | 范围 | 允许 | 限制 |\n|---|---|---|---|---|\n")
	for _, a := range identity.Actions() {
		level, allowed := "实例", "本人"
		if a.Level == identity.ProjectLevel {
			level = "项目"
			var rs []string
			for _, r := range a.Roles {
				rs = append(rs, string(r))
			}
			allowed = strings.Join(rs, "、")
			if a.AdminAlso {
				allowed += "；系统 admin"
			}
		} else if len(a.SystemRoles) > 0 {
			var rs []string
			for _, r := range a.SystemRoles {
				rs = append(rs, "系统 "+string(r))
			}
			allowed = strings.Join(rs, "、")
		}
		var notes []string
		if a.WorkerScope {
			notes = append(notes, "Worker 使用 worker 范围；仍核对项目角色")
		}
		if a.HumanOnly {
			notes = append(notes, "仅人本人")
		}
		if a.HumanGrant {
			notes = append(notes, "需 HumanGrant")
		}
		if a.RecoveryOnly {
			notes = append(notes, "仅恢复会话")
		}
		if a.AllowRecovery {
			notes = append(notes, "恢复会话可用")
		}
		fmt.Fprintf(&b, "| `%s` | %s | `%s` | %s | %s |\n", a.Action, level, a.Scope, allowed, strings.Join(notes, "；"))
	}

	b.WriteString("\n## 策略\n\n系统默认 → 实例覆盖 → 项目覆盖；固定项拒绝任何覆盖。\n\n| 策略 | 默认 | 允许取值 |\n|---|---|---|\n")
	for _, p := range identity.PolicyCatalog() {
		fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", p.Key, p.Default, p.Allowed)
	}
	return b.Bytes()
}
